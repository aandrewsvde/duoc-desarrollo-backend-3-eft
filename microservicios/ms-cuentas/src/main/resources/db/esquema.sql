-- =====================================================================
-- Banco XYZ - Esquema de ms-cuentas
--
-- Solo este microservicio toca estas tablas. Es la regla de "base de
-- datos por servicio": si ms-pagos pudiera escribir aqui, los
-- dos quedarian acoplados por el esquema y no se podrian desplegar ni
-- evolucionar por separado, que es justamente lo que se busca.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Numeracion de cuentas nuevas.
--
-- Arranca en 1000 y no en 1: los numeros 101 a 150 son los que trae la
-- migracion del sistema legado, y una secuencia que empezara por debajo
-- acabaria chocando con ellos. Dejar un hueco deliberado hace ademas que
-- de un vistazo se distinga una cuenta migrada de una abierta aqui.
--
-- La numeracion la lleva la base y no el codigo porque dos peticiones
-- simultaneas que calcularan el maximo por separado elegirian el mismo
-- numero; una secuencia no tiene esa condicion de carrera.
-- ---------------------------------------------------------------------
CREATE SEQUENCE IF NOT EXISTS seq_numero_cuenta START WITH 1000 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS cuenta (
    numero_cuenta  INTEGER       PRIMARY KEY,
    -- Referencia al titular en ms-clientes. Es un identificador, NO una clave
    -- foranea: la tabla de clientes vive en otra base, de otro servicio. Que
    -- no haya integridad referencial declarada aqui es el precio de la
    -- independencia, y se paga a sabiendas: a cambio, ms-clientes puede
    -- cambiar su esquema sin coordinar con este.
    cliente_id     INTEGER       NOT NULL,
    -- Nombre del titular desnormalizado. Duplica un dato de ms-clientes a
    -- proposito, para que consultar un saldo no obligue a una llamada de red
    -- adicional. Se acepta la copia porque el nombre casi nunca cambia y,
    -- cuando cambia, la fuente de verdad sigue siendo ms-clientes.
    titular        VARCHAR(120)  NOT NULL,
    tipo_cuenta    VARCHAR(20)   NOT NULL,
    saldo          NUMERIC(15,2) NOT NULL,
    moneda         VARCHAR(3)    NOT NULL DEFAULT 'CLP',
    estado         VARCHAR(20)   NOT NULL DEFAULT 'ACTIVA',
    abierta_en     TIMESTAMP     NOT NULL DEFAULT now(),
    cerrada_en     TIMESTAMP,
    actualizada_en TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT ck_cuenta_tipo   CHECK (tipo_cuenta IN ('AHORRO', 'PRESTAMO', 'HIPOTECA')),
    CONSTRAINT ck_cuenta_estado CHECK (estado IN ('ACTIVA', 'BLOQUEADA', 'CERRADA')),
    -- Una cuenta cerrada debe tener fecha de cierre y una abierta no. La regla
    -- se declara en la base y no solo en el codigo porque es una invariante
    -- del dato: cualquier via de escritura, incluida la migracion batch, debe
    -- respetarla.
    CONSTRAINT ck_cuenta_cierre CHECK (
        (estado = 'CERRADA' AND cerrada_en IS NOT NULL) OR
        (estado <> 'CERRADA' AND cerrada_en IS NULL))
);
CREATE INDEX IF NOT EXISTS ix_cuenta_cliente ON cuenta (cliente_id);

CREATE TABLE IF NOT EXISTS movimiento (
    -- GENERATED AS IDENTITY y no BIGSERIAL: es la sintaxis estandar, la
    -- entienden tanto PostgreSQL como el H2 de las pruebas, y asi estas
    -- ejercitan EXACTAMENTE este archivo en lugar de una copia que puede
    -- divergir sin que nadie lo note.
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id      INTEGER       NOT NULL REFERENCES cuenta (numero_cuenta),
    -- Identificador del pago que lo origino. Es NULL en los movimientos
    -- historicos migrados del legado, que no nacieron de un pago de este
    -- sistema sino del arrastre de la migracion.
    pago_id        VARCHAR(60),
    fecha          DATE          NOT NULL,
    tipo           VARCHAR(20)   NOT NULL,
    signo          SMALLINT      NOT NULL,
    monto          NUMERIC(15,2) NOT NULL,
    descripcion    VARCHAR(200)  NOT NULL,
    origen         VARCHAR(20)   NOT NULL DEFAULT 'LEGACY',
    registrado_en  TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT ck_movimiento_signo CHECK (signo IN (1, -1)),
    CONSTRAINT ck_movimiento_monto CHECK (monto > 0)
);
CREATE INDEX IF NOT EXISTS ix_movimiento_cuenta_fecha ON movimiento (cuenta_id, fecha DESC, id DESC);

-- ---------------------------------------------------------------------
-- Bitacora de eventos ya aplicados.
--
-- Kafka garantiza entrega "al menos una vez": tras un reequilibrio de
-- particiones o un reinicio del consumidor, el mismo evento puede llegar
-- dos veces. Sin esta tabla, ese reintento descontaria el dinero de nuevo.
--
-- La clave primaria sobre evento_id es lo que hace idempotente el
-- consumo: la segunda insercion choca contra el indice y el pago
-- se aborta antes de tocar el saldo. Es la base de datos la que lo
-- garantiza y no una consulta previa en el codigo, que dos consumidores
-- simultaneos podrian sortear entre el SELECT y el UPDATE.
-- ---------------------------------------------------------------------
-- ---------------------------------------------------------------------
-- Bitacora de cambios de estado de una cuenta.
--
-- Apertura, bloqueo y cierre son operaciones poco frecuentes pero de alto
-- impacto, y son las primeras que pregunta una auditoria. Guardar solo el
-- estado actual responde "como esta"; esta tabla responde "quien lo hizo,
-- cuando y por que", que es lo que realmente se audita.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS cuenta_bitacora (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id     INTEGER      NOT NULL,
    estado_previo VARCHAR(20),
    estado_nuevo  VARCHAR(20)  NOT NULL,
    motivo        VARCHAR(200) NOT NULL,
    solicitado_por VARCHAR(80) NOT NULL,
    ocurrido_en   TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_bitacora_cuenta ON cuenta_bitacora (cuenta_id, ocurrido_en DESC);

CREATE TABLE IF NOT EXISTS evento_procesado (
    evento_id    VARCHAR(60) PRIMARY KEY,
    topico       VARCHAR(80) NOT NULL,
    resultado    VARCHAR(20) NOT NULL,
    procesado_en TIMESTAMP   NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Este archivo NO borra datos.
--
-- Se ejecuta en CADA arranque del servicio, de modo que un DELETE aqui
-- convertiria cualquier reinicio -un despliegue, una caida, escalar a
-- mas replicas- en una perdida de datos silenciosa. Eso fue exactamente
-- lo que ocurrio al probar la recuperacion de un servicio caido: volvio
-- sano y sin nada dentro.
--
-- Los datos los pone la migracion batch y se reinician donde corresponde:
-- borrando el volumen de PostgreSQL (scripts/detener.sh --limpiar) y
-- volviendo a migrar. Las sentencias CREATE llevan IF NOT EXISTS, asi que
-- reejecutar este archivo es inocuo.
-- ---------------------------------------------------------------------
